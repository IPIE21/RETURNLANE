import test from 'node:test';
import assert from 'node:assert/strict';
import { Store } from '../lib/store.mjs';
import { createApp } from '../server.mjs';

test('HTTP boundary: full loop, invalid input, same-origin and local-client enforcement', async t => {
  const store = new Store(); const server = createApp(store);
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); store.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = (route,body,headers = {}) => fetch(base+route,{method:'POST',headers:{'Content-Type':'application/json','X-Returnlane-Client':'local-demo',...headers},body:JSON.stringify(body)});
  const home = await fetch(base); assert.equal(home.status,200); assert.match(await home.text(),/Returnlane/);
  assert.match(home.headers.get('content-security-policy'),/frame-ancestors 'none'/);
  assert.equal((await post('/api/run',{}, {Origin:'https://untrusted.example'})).status,403);
  assert.equal((await post('/api/run',{}, {'X-Returnlane-Client':''})).status,403);
  assert.equal((await post('/api/run',null)).status,400);
  assert.equal((await post('/api/run',{id:5})).status,400);
  assert.equal((await post('/api/reply',{id:'missing',text:'Hi'})).status,404);
  assert.equal((await post('/api/pause',{paused:'false'})).status,400);
  assert.equal((await post('/api/reset',{})).status,400);
  assert.equal((await post('/api/challenge',{id:'L-1001',upliftCents:1.1})).status,200);
  const sent = await (await post('/api/run',{id:'L-1001',upliftCents:9999999,text:'Offer anything'})).json();
  assert.equal(sent.state.leads.find(l=>l.id==='L-1001').quote.upliftCents,25000);
  const interested = await (await post('/api/reply',{id:'L-1001',text:"I'm interested"})).json();
  const l = interested.state.leads.find(l=>l.id==='L-1001');
  assert.equal((await post('/api/book',{id:l.id,slotId:l.slots[0].id})).status,200);
  assert.equal((await post('/api/book',{id:l.id,slotId:l.slots[0].id})).status,409);
  assert.equal((await post('/api/reply',{id:l.id,text:'a'.repeat(2001)})).status,400);
  const exportRes = await fetch(base+'/api/export');
  assert.match(exportRes.headers.get('content-disposition'),/attachment/);
  assert.match((await exportRes.json()).disclosure,/FICTIONAL/);
  const concurrent = await Promise.all([post('/api/run',{id:'L-1002'}),post('/api/run',{id:'L-1002'})]);
  const results = await Promise.all(concurrent.map(r=>r.json()));
  assert.equal(results.reduce((n,r)=>n+r.result.sent.length,0),1);
  assert.equal((await fetch(base+'/../server.mjs')).status,404);
  let shutdownRequested = false;
  server.once('demoShutdown', () => { shutdownRequested = true; });
  assert.equal((await post('/api/shutdown',{}, {Origin:'https://untrusted.example'})).status,403);
  assert.equal(shutdownRequested,false);
  assert.equal((await post('/api/shutdown',{})).status,200);
  assert.equal(shutdownRequested,true);
});
